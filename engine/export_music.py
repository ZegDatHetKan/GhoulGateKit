def main(out):
    os.makedirs(out, exist_ok=True)
    ff = imageio_ffmpeg.get_ffmpeg_exe()
    rows = ['| # | Track | Used for | Length |', '|---|---|---|---|']
    for fn, title, use, gen in CUES:
        x = gen()
        x = x[0] if isinstance(x, tuple) else x
        x = np.asarray(x, dtype=np.float32)
        if x.ndim == 1:
            x = np.stack([x, x], 1)
        n = min(len(x), int(3.0 * M.SR))
        x[-n:] *= np.linspace(1, 0, n)[:, None]                                   # clean ending on every track
        x = x / max(1e-6, np.abs(x).max()) * .89
        tmp = os.path.join(out, fn + '.wav')
        with wave.open(tmp, 'wb') as w:
            w.setnchannels(2); w.setsampwidth(2); w.setframerate(M.SR)
            w.writeframes((x * 32767).astype('<i2').tobytes())
        subprocess.run([ff, '-y', '-v', 'error', '-i', tmp, '-b:a', '320k', '-metadata', f'title={title}',
                        '-metadata', 'album=GhoulGate OST', os.path.join(out, fn + '.mp3')], check=True)
        os.remove(tmp)
        rows.append(f'| {fn[:2]} | {title} | {use} | {len(x) / M.SR:.0f}s |')
        print(fn, f'{len(x) / M.SR:.1f}s')
    open(os.path.join(out, 'TRACKLIST.md'), 'w').write('# GhoulGate OST\n\nAll cues generated by `engine/music.py` '
                                                        '(arrangements in `series_bible/07_music_and_sfx.md`).\n\n' + '\n'.join(rows) + '\n')


if __name__ == '__main__':
    main(sys.argv[1])
